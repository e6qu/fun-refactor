def main() -> None:
    print("start")
    a = 7
    b = 2
    print(f"sum {a + b}")
    print(f"diff {a - b}")
    print(f"product {a * b}")
    print(f"quotient {a // b}")
    print(f"remainder {a % b}")
    negative = -7
    print(f"negquotient {negative // b}")
    print(f"negremainder {negative % b}")
    print("done")


if __name__ == "__main__":
    main()
